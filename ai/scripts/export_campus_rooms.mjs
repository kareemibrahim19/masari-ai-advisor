// Writes ai/chatbot/tools/campus_rooms.json from the website's campus map (frontend/src/lib/campus-map/data.ts),
// so the chatbot's room_location tool knows the same rooms as the map. Run again after changing the map:
//     node ai/scripts/export_campus_rooms.mjs
// (Node 22.18+ reads the TypeScript file directly.)
import { writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { BUILDINGS, rooms } from "../../frontend/src/lib/campus-map/data.ts"

const out = fileURLToPath(new URL("../chatbot/tools/campus_rooms.json", import.meta.url))
const building = (space) => BUILDINGS.find((b) => b.space === space)
// A room without a number is linked by its name, so only names that belong to one room can be linked.
const nameCount = {}
for (const r of rooms) nameCount[r.name.ar] = (nameCount[r.name.ar] ?? 0) + 1

const list = rooms
  .filter((r) => r.code || nameCount[r.name.ar] === 1)
  .map((r) => ({
    code: r.code ?? null,
    name_ar: r.name.ar,
    name_en: r.name.en,
    building_ar: building(r.space).name.ar,
    building_en: building(r.space).name.en,
    part_ar: r.bld.ar,
    floor_ar: building(r.space).floors[r.f].ar,
    floor_en: building(r.space).floors[r.f].en,
    inferred: Boolean(r.inferred),
    map_room: r.code ?? r.name.ar,
  }))
writeFileSync(out, JSON.stringify({ _note: "Generated by ai/scripts/export_campus_rooms.mjs from the website's campus map. Do not edit by hand.", rooms: list }, null, 1) + "\n")
console.log(`${list.length} rooms -> ${out}`)

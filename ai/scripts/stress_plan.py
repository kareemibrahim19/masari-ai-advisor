# ================================================================ the rules, read from courses.json only

def prereqs(code: str) -> list[str]:
    """Prerequisites, plus the previous project (projects go 1 -> 2 -> 3)."""
    out = list(C[code]["prerequisites"])
    if code in PROJECTS[1:]:
        out.append(PROJECTS[PROJECTS.index(code) - 1])
    return list(dict.fromkeys(out))


def hours_least(code: str) -> int:
    """Hours a course can be registered with (projects: with the paper-registration tolerance)."""
    c = C[code]
    return (c.get("min_credits_required") or 0) - (c.get("min_credits_tolerance") or 0)


def runs_in(code: str, kind: str, summer: bool) -> bool:
    """Whether a course can be taken in a term of this kind (without a special request)."""
    t = C[code]["type"]
    if kind == "summer":
        return t == "training" or (summer and t != "project")
    if t in ("training", "elective", "project"):
        return True  # training in a main term needs the college's approval, still allowed
    return (C[code]["planned_semester"] % 2 == 1) == (kind == "fall")


def cap_for(cgpa, main_done: int) -> int:
    """Article 13 / 25 as in courses.json: the hour cap of the next main term."""
    if cgpa is None:
        return 21
    if cgpa < R["warning_gpa_threshold"] and main_done >= R["warning_starts_after_main_semester"]:
        return R["probation_max_credits"]
    return next(b["max_credits"] for b in R["max_credits_by_gpa"] if b["gpa_min"] <= cgpa < b["gpa_max"])


WITHDRAWN, DEPRIVED = "W", "DN"  # a withdrawal is not an attempt; a deprivation counts as 0 in the GPA


def best_attempts(terms: list[dict]) -> dict:
    best = {}
    for t in terms:
        if t["status"] == "published":
            for c in t["courses"]:
                if c.get("grade") != WITHDRAWN:
                    best[c["code"]] = c
    return best


def is_pass(grade: str) -> bool:
    return grade == "P" or (grade in GP and grade not in ("F", DEPRIVED))


def cgpa_of(terms: list[dict]):
    g = [a for a in best_attempts(terms).values() if a["grade"] in GP]
    h = sum(a["credits"] for a in g)
    return round(sum(GP[a["grade"]] * a["credits"] for a in g) / h, 2) if h else None


def projection(rec: dict, failed=(), term_gpa=None) -> dict:
    """Where the student stands once the current term is graded: every current course passes except `failed`,
    with grades at the current GPA, or sharing the points of `term_gpa` (the planner's stated assumption,
    recomputed here)."""
    terms = rec["terms"]
    best = best_attempts(terms)
    cur = next((t for t in terms if t["status"] == "in_progress"), None) or terms[-1]  # else frozen (وقف قيد)
    cur_codes = {c["code"] for c in cur["courses"]}
    passed = ({c for c, a in best.items() if is_pass(a["grade"])} | cur_codes) - set(failed)
    old = [a for c, a in best.items() if a["grade"] in GP and c not in cur_codes]
    h = sum(a["credits"] for a in old)
    p = sum(GP[a["grade"]] * a["credits"] for a in old)
    now = [c for c in cur["courses"] if C[c["code"]].get("graded", True) and C[c["code"]]["credits"] > 0]
    nh = sum(C[c["code"]]["credits"] for c in now)
    ph = sum(C[c["code"]]["credits"] for c in now if c["code"] not in failed)
    g0 = rec["academic_status"]["cumulative_gpa"]
    if term_gpa is not None:
        per = term_gpa * nh / ph if ph else 0.0
    else:
        per = 2.5 if g0 is None else g0
    cgpa = round((p + per * ph) / (h + nh), 2) if h + nh else g0
    main_now = rec["academic_status"]["main_semesters_completed"] + (0 if cur["term"] == "summer"
                                                                     or cur["status"] == "frozen" else 1)
    return {"passed": passed, "earned": sum(C[c]["credits"] for c in passed), "cgpa": cgpa, "main_now": main_now,
            "cur": cur, "graded": h + nh, "points": p + per * ph}


def remaining(passed: set) -> tuple[list[str], list[tuple[int, list[str]]]]:
    req = [c for c, x in C.items() if x["type"] != "elective" and c not in passed]
    pools = []
    for p in POOLS:
        need = max(0, p["choose"] - sum(1 for c in p["courses"] if c in passed))
        if need:
            pools.append((need, [c for c in p["courses"] if c not in passed]))
    return req, pools


def terms_after(kind: str, year: int, main_now: int, last_main: int, summer_after: bool = True) -> list[dict]:
    """Terms after the current one, up to main semester `last_main` and the summer right after it (the summer of the
    last year counts in the target, confirmed 2026-10-17). year = start of the academic year."""
    out, m = [], main_now
    while True:
        kind = NEXT[kind]
        if kind == "fall":
            year += 1
        if kind != "summer":
            m += 1
        if m > last_main or (kind == "summer" and m == last_main and not summer_after):
            return out
        out.append({"term": kind, "year": year, "main": m if kind != "summer" else None})


def caps_of(terms: list[dict], cap: int, hi_from) -> list:
    """Cap of each main term: the GPA band, 14 -> 12 once academic warning starts, 21 from `hi_from` (the GPA route)."""
    out, j = [], 0
    for t in terms:
        if t["main"] is None:
            out.append(None)
            continue
        c = cap
        if cap == 14 and t["main"] - 1 >= R["warning_starts_after_main_semester"]:
            c = R["probation_max_credits"]
        if hi_from is not None and j >= hi_from:
            c = 21
        out.append(c)
        j += 1
    return out


# ================================================================ the independent solver

def oracle(passed: set, earned: int, cap: int, kind: str, year: int, main_now: int, last_main: int,
           summer: bool, hi_from=None, request: bool = True, summer_after: bool = True, min12: bool = False):
    """Is there ANY schedule of the remaining courses that finishes by main semester `last_main` (and its summer)?

    Rules (courses.json and what the team confirmed): each course once, prerequisites in an earlier term, offering
    (term of the plan semester, electives and projects in fall or spring, summer any non-project up to 6 hours,
    training any term), hour thresholds with the projects' tolerance, the hour cap (15 on paper in a 14-hour term of
    3-hour courses), no empty main semester before graduation (and no summer after an empty one), and a mandatory
    course outside its semester only by request: one in the graduation semester, or one alone in a semester where
    nothing else is taken. The 12-hour minimum is soft (council approval) unless `min12`.
    Returns the schedule {code: term index} or None.
    """
    terms = terms_after(kind, year, main_now, last_main, summer_after)
    req, pools = remaining(passed)
    if not req and not pools:
        return {}
    if not terms:
        return None
    caps = caps_of(terms, cap, hi_from)
    items = req + [c for _, cs in pools for c in cs]
    var, off = [], []  # (code, term), whether it is opened by request
    for c in items:
        for ti, t in enumerate(terms):
            if runs_in(c, t["term"], summer):
                var.append((c, ti)), off.append(False)
            elif request and t["main"] is not None and C[c]["type"] == "mandatory":
                var.append((c, ti)), off.append(True)
    nx = len(var)
    lows = [ti for ti, cp in enumerate(caps) if cp == 14]
    mains = [ti for ti, t in enumerate(terms) if t["main"] is not None]
    A_, S_ = nx + len(lows), nx + len(lows) + len(mains)  # "active" and "only requested" per main term
    n = S_ + len(mains)
    rows, cols, vals, lo, hi = [], [], [], [], []

    def add(co: dict, a, b):
        r = len(lo)
        for k, v in co.items():
            rows.append(r), cols.append(k), vals.append(v)
        lo.append(a), hi.append(b)

    by_code = defaultdict(list)
    for k, (c, _) in enumerate(var):
        by_code[c].append(k)
    for c in req:
        if not by_code[c]:
            return None
        add({k: 1 for k in by_code[c]}, 1, 1)
    for need, cs in pools:
        for c in cs:
            if by_code[c]:
                add({k: 1 for k in by_code[c]}, 0, 1)
        ks = [k for c in cs for k in by_code[c]]
        if len({var[k][0] for k in ks}) < need:
            return None
        add({k: 1 for k in ks}, need, need)
    for k, (c, ti) in enumerate(var):
        for p in prereqs(c):
            if p in passed:
                continue
            if p not in by_code:
                return None
            add({k: 1, **{k2: -1 for k2 in by_code[p] if var[k2][1] < ti}}, -np.inf, 0)
        need = hours_least(c)
        if need > earned:
            co = {k2: -C[var[k2][0]]["credits"] for k2 in range(nx) if var[k2][1] < ti and C[var[k2][0]]["credits"]}
            add({**co, k: need}, -np.inf, earned)
    for ti, t in enumerate(terms):
        ks = [k for k in range(nx) if var[k][1] == ti]
        if not ks:
            continue
        cr = {k: C[var[k][0]]["credits"] for k in ks}
        if t["main"] is None:
            add(cr, -np.inf, SUMMER_MAX)
        elif ti in lows:
            w = nx + lows.index(ti)
            add({**cr, w: -1}, -np.inf, 14)  # 15 on paper ...
            for k in ks:
                if C[var[k][0]]["credits"] not in (0, 3):  # ... only with 3-hour courses
                    add({k: 1, w: 1}, -np.inf, 1)
        else:
            add(cr, -np.inf, caps[ti])
    for j, ti in enumerate(mains):
        ks = [k for k in range(nx) if var[k][1] == ti]
        a, solo = A_ + j, S_ + j
        nxt = {A_ + j + 1: 1} if j + 1 < len(mains) else {}
        for k in ks:
            add({k: 1, a: -1}, -np.inf, 0)  # a course makes the term active ...
        add({a: 1, **{k: -1 for k in ks}}, -np.inf, 0)  # ... and an active term has a course
        if nxt:
            add({a: 1, A_ + j + 1: -1}, 0, np.inf)  # no empty main semester before one with courses
        reqs = [k for k in ks if off[k]]
        if reqs:
            add({k: 1 for k in reqs}, 0, 1)
            for k in reqs:  # graduation semester (active, the next one not) or a semester of only that course
                add({k: 1, a: -1, **nxt, solo: -1}, -np.inf, 0)
            for k in ks:
                if not off[k]:
                    add({k: 1, solo: 1}, -np.inf, 1)
        if min12 and nxt:  # 12 hours in every semester before the graduation one
            add({**{k: C[var[k][0]]["credits"] for k in ks}, A_ + j + 1: -R["min_credits_main_semester"]}, 0, np.inf)
    for si, t in enumerate(terms):  # a summer has courses only after a main semester with courses
        if t["main"] is None and si - 1 in mains:
            for k in range(nx):
                if var[k][1] == si:
                    add({k: 1, A_ + mains.index(si - 1): -1}, -np.inf, 0)
    A = coo_matrix((vals, (rows, cols)), shape=(len(lo), n)).tocsr()
    res = milp(np.zeros(n), integrality=np.ones(n), bounds=Bounds(0, 1), constraints=LinearConstraint(A, lo, hi),
               options={"time_limit": 60})
    if res.status == 0 and res.x is not None:
        return {var[k][0]: var[k][1] for k in range(nx) if res.x[k] > 0.5}
    if res.status == 2:
        return None
    raise RuntimeError(f"oracle solver status {res.status}: {res.message}")


def oracle_earliest(pj: dict, cap: int, summer: bool, start: int, stop: int):
    """The earliest main semester in [start, stop] the independent solver can finish by (None if none)."""
    kind, year = pj["cur"]["term"], int(pj["cur"]["academic_year"].split("-")[0])
    for last in range(max(start, pj["main_now"]), stop + 1):
        if oracle(pj["passed"], pj["earned"], cap, kind, year, pj["main_now"], last, summer) is not None:
            return last
    return None


# ================================================================ checking a plan

def plan_problems(pj: dict, plan: dict, summer: bool, cap: int) -> list[str]:
    """Rules the shown plan breaks, checked from courses.json (empty = the plan can really be followed)."""
    out = []
    passed, earned = set(pj["passed"]), pj["earned"]
    rows = plan.get("terms") or []
    if pj["cur"]["status"] == "frozen" and rows:
        if not rows[0].get("frozen") or rows[0]["courses"]:
            out.append("موقف قيده الترم ده والخطة مبتبيّنش ده في أولها")
        else:
            rows = rows[1:]
    conds = {c["kind"] for c in plan.get("conditions", [])}
    summer = summer or "summer" in conds
    hi_from = (plan.get("gpa_needed") or {}).get("from") if "gpa" in conds else None
    kind, year = pj["cur"]["term"], int(pj["cur"]["academic_year"].split("-")[0])
    expect = terms_after(kind, year, pj["main_now"], pj["main_now"] + len(rows) + 2)
    caps = caps_of(expect, cap, hi_from)
    seen, done_hours = set(passed), earned
    improvement = plan.get("improvement")
    last_main_row = max((i for i, r in enumerate(rows) if r["term"] != "summer" and r["courses"]), default=-1)
    j = 0
    for i, r in enumerate(rows):
        while j < len(expect) and expect[j]["term"] == "summer" and r["term"] != "summer":
            j += 1  # an empty summer left out of the plan
        if j >= len(expect) or (expect[j]["term"], expect[j]["year"]) != (r["term"], int(r["academic_year"][:4])):
            out.append(f"الترم رقم {i + 1} في الخطة ({r['term']} {r['academic_year']}) مش الترم اللي بعد اللي قبله")
            break
        cp_i, j = caps[j], j + 1
        codes = [c["code"] for c in r["courses"]]
        hours = sum(C[c]["credits"] for c in codes)
        if hours != r["credits"]:
            out.append(f"مجموع ساعات {r['ar']} غلط")
        for c in codes:
            if improvement and c in improvement["courses"]:
                continue
            if c in seen:
                out.append(f"{c} متحطة مرتين أو هو ناجح فيها")
            for p in prereqs(c):
                if p not in seen:
                    out.append(f"{c} في {r['ar']} قبل متطلبها {p}")
            if done_hours < hours_least(c):
                out.append(f"{c} في {r['ar']} ومعاه {done_hours} ساعة بس (محتاج {hours_least(c)})")
            flag = next(x["flag"] for x in r["courses"] if x["code"] == c)
            if not runs_in(c, r["term"], summer):
                grad_req = flag == "graduation_request" and i == last_main_row
                open_req = flag == "open_request" and len(codes) == 1
                if r["term"] == "summer" or not (grad_req or open_req):
                    out.append(f"{c} في {r['ar']} وهي مش بتتدرّس فيه ({flag})")
        n_req = sum(1 for x in r["courses"] if x["flag"] in ("graduation_request", "open_request"))
        for x in r["courses"]:
            if x["flag"] in ("graduation_request", "open_request") and not (x.get("paper_registration") and x.get("paper_opened")):
                out.append(f"{x['code']} في {r['ar']} مفتوحة بطلب ومش متعلّمة تسجيل ورقي")
        if r["term"] != "summer" and not codes and i < len(rows) - 1:
            out.append(f"{r['ar']} فاضي وبعده ترمات فيها مواد")
        if r["term"] == "summer" and codes and i > 0 and rows[i - 1]["term"] != "summer" and not rows[i - 1]["courses"]:
            out.append(f"{r['ar']} فيه مواد بعد ترم أساسي فاضي")
        if r["term"] == "summer":
            if hours > SUMMER_MAX:
                out.append(f"{hours} ساعة في {r['ar']} (الصيفي أقصاه {SUMMER_MAX})")
        else:
            cp = cp_i
            paper15 = cp == 14 and hours == 15 and all(C[c]["credits"] in (0, 3) for c in codes)
            if hours > cp and not paper15 and not improvement:
                out.append(f"{hours} ساعة في {r['ar']} فوق الحد {cp}")
            if improvement and hours > cap:
                out.append(f"{hours} ساعة تحسين في {r['ar']} فوق الحد {cap}")
        if n_req > 1:
            out.append(f"أكتر من مادة بطلب في {r['ar']}")
        seen |= set(codes)
        done_hours += hours
    if improvement:
        return out
    req, pools = remaining(seen)
    if rows and (req or pools):
        out.append("الخطة خلصت ولسه فاضل: " + "، ".join(req + [f"{n} اختياري" for n, _ in pools]))
    if rows and done_hours < R["graduation"]["min_credits"]:
        out.append(f"الخطة بتوصل {done_hours} ساعة بس (المطلوب {R['graduation']['min_credits']})")
    return out



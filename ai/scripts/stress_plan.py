def work(args):
    rec, follow = args
    try:
        return check_one(rec, follow)
    except Exception as e:  # noqa: BLE001
        return {"sid": rec["student_id"], "meta": rec["meta"], "cells": {}, "notes": [],
                "problems": [{"kind": "crash", "text": f"الاختبار وقع: {e!r}", "trace": traceback.format_exc()[-1500:]}]}


def build_students(n: int) -> list[dict]:
    rng = random.Random("masari-stress")
    out = edge_cases()
    i = 0
    while len(out) < n + len(edge_cases()):
        i += 1
        maker = transfer if rng.random() < 0.2 else lived
        s = maker(rng, f"ST-{i:05d}")
        if s:
            out.append(s)
    return out


def kept(results: list[dict], students: list[dict]) -> list[dict]:
    """Full records only of the students something went wrong for (the rest come back with the same seed)."""
    keep = {r["sid"] for r in results if r["problems"] or (r.get("follow") or {}).get("ok") is False}
    for r in results:
        if r.get("follow"):
            r["follow"].pop("log", None)
    return [s for s in students if s["student_id"] in keep]


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 1500
    students = build_students(n)
    follow_every = 4  # one student in four also follows the plan to the end
    jobs = [(s, i % follow_every == 0 or s["meta"]["kind"] == "edge") for i, s in enumerate(students)]
    t0 = time.time()
    results = []
    with Pool(max(1, min(6, (os.cpu_count() or 2) - 2))) as pool:
        for k, r in enumerate(pool.imap_unordered(work, jobs, chunksize=2), 1):
            results.append(r)
            if k % 100 == 0:
                bad = sum(1 for x in results if x["problems"])
                print(f"{k}/{len(jobs)}  {time.time() - t0:.0f}s  students with problems: {bad}", flush=True)
    results.sort(key=lambda r: r["sid"])
    meta = {"students": len(results), "seconds": round(time.time() - t0), "seed": "masari-stress",
            "by_kind": Counter(r["meta"]["kind"] for r in results)}
    OUT.mkdir(exist_ok=True)
    (OUT / "plan_stress.json").write_text(json.dumps({"meta": meta, "results": results, "students": kept(results, students)},
                                                     ensure_ascii=False, default=list), encoding="utf-8")
    kinds = Counter(p["kind"] for r in results for p in r["problems"])
    print(json.dumps({"students": len(results), "problems": kinds}, ensure_ascii=False))


if __name__ == "__main__":
    main()

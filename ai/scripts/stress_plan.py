GRADES = [g["grade"] for g in R["grade_scale"]]


def letter(pct: float) -> str:
    return next(g["grade"] for g in R["grade_scale"] if pct >= g["min_percent"])


def year_of(kind: str, start: int) -> str:
    return f"{start}-{start + 1}"


PROFILES = {
    # name: (mean %, sd, failure probability, summer probability, load style)
    "excellent": (93, 4, 0.00, 0.3, "full"),
    "good": (84, 5, 0.03, 0.3, "full"),
    "average": (76, 6, 0.08, 0.4, "full"),
    "weak": (68, 6, 0.18, 0.4, "full"),
    "struggling": (63, 4, 0.30, 0.3, "full"),
    "part_time": (82, 6, 0.05, 0.1, "part"),
    "summer_heavy": (78, 6, 0.08, 0.95, "full"),
    "no_summer": (78, 6, 0.08, 0.0, "full"),
    "erratic": (75, 12, 0.15, 0.4, "random"),
}


def grade_for(rng, prof, code, retake) -> str:
    """A grade for a course: a withdrawal now and then (W), a failure by the profile's rate, some of them for
    absence (DN, counts as 0), else a letter (a retake after a failure is capped at B+)."""
    mean, sd, pf = PROFILES[prof][:3]
    if rng.random() < 0.03:
        return WITHDRAWN
    if C[code].get("graded", True) is False:
        return "FP" if rng.random() < pf else "P"
    if rng.random() < pf:
        return DEPRIVED if rng.random() < 0.15 else "F"
    g = letter(min(100, max(60, rng.gauss(mean, sd))))
    if retake and GRADES.index(g) < GRADES.index(R["retake_max_grade"]):
        g = R["retake_max_grade"]
    return g


def pick(rng, rec_terms, passed, earned, kind, cgpa, main_done, prof, first) -> list[str]:
    """Courses a student registers this term: what runs and is open to them, lowest plan semester first."""
    in_pool_done = {i: sum(1 for c in p["courses"] if c in passed) for i, p in enumerate(POOLS)}
    avail = []
    for c, x in C.items():
        if c in passed:
            continue
        if any(p not in passed for p in prereqs(c)):
            continue
        if earned < hours_least(c) or (x["type"] == "training" and earned < (x.get("min_credits_required") or 0)):
            continue
        if kind == "summer":
            if x["type"] == "project":
                continue
            if x["type"] == "training":
                avail.append(c)
                continue
        elif x["type"] == "training" and rng.random() > 0.15:
            continue  # training is a summer thing, a main term only now and then
        elif x["type"] == "mandatory" and not runs_in(c, kind, False):
            continue
        if x["type"] == "elective":
            i = next(i for i, p in enumerate(POOLS) if c in p["courses"])
            if in_pool_done[i] >= POOLS[i]["choose"]:
                continue
        avail.append(c)
    slot = {s["slot"]: s["semester"] for s in PROGRAM["elective_slots"]}
    sem = lambda c: C[c]["planned_semester"] or min(slot[s] for p in POOLS if c in p["courses"] for s in p["slots"])
    rng.shuffle(avail)
    avail.sort(key=lambda c: sem(c) + rng.random() * 2)
    if kind == "summer":
        limit = SUMMER_MAX
    elif first:
        limit = 18
    else:
        limit = cap_for(cgpa, main_done)
        style = PROFILES[prof][4]
        if style == "part":
            limit = min(limit, rng.choice([12, 12, 13, 15]))
        elif style == "random":
            limit = min(limit, rng.randint(9, limit))
    chosen, load, per_pool = [], 0, dict(in_pool_done)
    for c in avail:
        cr = C[c]["credits"]
        if load + cr > limit:
            continue
        if C[c]["type"] == "elective":
            i = next(i for i, p in enumerate(POOLS) if c in p["courses"])
            if per_pool[i] >= POOLS[i]["choose"]:
                continue
            per_pool[i] += 1
        if C[c]["type"] == "project" and any(x in PROJECTS for x in chosen):
            continue
        chosen.append(c)
        load += cr
    return chosen


def lived(rng, sid: str) -> dict:
    """A student who lived a random history: profile, number of terms, summers and the current term."""
    prof = rng.choice(list(PROFILES))
    if rng.random() < 0.25:  # some profiles change half way (a bad year, a recovery)
        prof2, switch = rng.choice(list(PROFILES)), rng.randint(2, 8)
    else:
        prof2, switch = prof, 99
    mains = rng.choice([0, 0, 1, 1, 2, 3, 4, 5, 6, 7, 8, 8, 9, 9, 10, 11, 12, 13])
    kind, year = "fall", 2026 - (mains // 2) - (1 if mains % 2 else 0)
    terms, main_done, streak, freezes = [], 0, 0, 0
    p_cur = prof
    while True:
        best = best_attempts(terms)
        passed = {c for c, a in best.items() if is_pass(a["grade"])}
        earned = sum(C[c]["credits"] for c in passed)
        cg = cgpa_of(terms)
        if kind != "summer" and main_done == mains:
            break
        if kind == "summer" and main_done == mains and rng.random() < 0.5:
            break  # the current term is a summer
        if main_done >= switch:
            p_cur = prof2
        if kind != "summer" and terms and rng.random() < 0.03:
            freezes += 1  # a frozen semester (وقف قيد): nothing registered, and it does not count
            terms.append({"term": kind, "academic_year": year_of(kind, year), "status": "frozen", "courses": []})
            kind = NEXT[kind]
            continue
        go_summer = kind != "summer" or rng.random() < PROFILES[p_cur][3]
        codes = pick(rng, terms, passed, earned, kind, cg, main_done, p_cur, not terms) if go_summer else []
        if codes:
            attempted = {c["code"] for t in terms for c in t["courses"] if c["grade"] != WITHDRAWN}
            rows = [{"code": c, "credits": C[c]["credits"],
                     "grade": grade_for(rng, p_cur, c, c in attempted)} for c in codes]
            terms.append({"term": kind, "academic_year": year_of(kind, year), "status": "published", "courses": rows})
        if kind != "summer":
            main_done += 1
            g = cgpa_of(terms)
            streak = streak + 1 if g is not None and g < 2 and main_done >= R["warning_starts_after_main_semester"] else 0
        kind = NEXT[kind]
        if kind == "fall":
            year += 1
    best = best_attempts(terms)
    passed = {c for c, a in best.items() if is_pass(a["grade"])}
    earned = sum(C[c]["credits"] for c in passed)
    cg = cgpa_of(terms)
    frozen_now = kind != "summer" and bool(terms) and rng.random() < 0.05
    if frozen_now:  # frozen right now: the plan starts with the semester after this one
        terms.append({"term": kind, "academic_year": year_of(kind, year), "status": "frozen", "courses": []})
    else:
        cur = pick(rng, terms, passed, earned, kind, cg, main_done, p_cur, not terms)
        if not cur:  # nothing open this term (e.g. an empty summer): take the next main term instead
            return None
        terms.append({"term": kind, "academic_year": year_of(kind, year), "status": "in_progress",
                      "courses": [{"code": c, "credits": C[c]["credits"]} for c in cur]})
    grades = Counter(c.get("grade") for t in terms for c in t["courses"])
    return record(sid, terms, main_done, {"kind": "lived", "profile": prof if prof == prof2 else f"{prof}→{prof2}",
                                          "mains": mains, "W": grades[WITHDRAWN], "DN": grades[DEPRIVED],
                                          "freezes": freezes, "frozen_now": bool(frozen_now)}, streak)


def transfer(rng, sid: str) -> dict:
    """A student whose passed courses are a random prerequisite-closed set (equivalences from another program)."""
    f = rng.uniform(0.1, 0.95)
    order = sorted(C, key=lambda c: (C[c]["planned_semester"] or 8, rng.random()))
    passed = []
    for c in order:
        if all(p in passed for p in prereqs(c)) and rng.random() < f:
            if C[c]["type"] == "elective":
                pool = next(p for p in POOLS if c in p["courses"])
                if sum(1 for x in pool["courses"] if x in passed) >= pool["choose"]:
                    continue
            passed.append(c)
    earned = sum(C[c]["credits"] for c in passed)
    passed = [c for c in passed if earned >= (C[c].get("min_credits_required") or 0) or C[c]["type"] != "training"]
    earned = sum(C[c]["credits"] for c in passed)
    main_done = max(1, min(14, round(earned / rng.uniform(14, 20))))
    mean = rng.uniform(62, 95)
    rows = [{"code": c, "credits": C[c]["credits"],
             "grade": "P" if C[c].get("graded", True) is False else letter(min(100, max(60, rng.gauss(mean, 6))))}
            for c in passed]
    if rng.random() < 0.4:  # a few failed courses too
        fails = [c for c in C if c not in passed and all(p in passed for p in prereqs(c))
                 and C[c].get("graded", True) and C[c]["type"] != "project"]
        rows += [{"code": c, "credits": C[c]["credits"], "grade": "F"} for c in rng.sample(fails, min(len(fails), rng.randint(1, 3)))]
    year = 2026 - math.ceil(main_done / 2)
    kind = rng.choice(["fall", "fall", "spring", "summer"])
    start = 2026 if kind == "fall" else 2025
    terms = [{"term": "spring", "academic_year": year_of("spring", min(year, start - 1)), "status": "published",
              "courses": rows}]
    cg = cgpa_of(terms)
    cur = pick(rng, terms, set(passed), earned, kind, cg, main_done, "average", False)
    if not cur:
        return None
    terms.append({"term": kind, "academic_year": year_of(kind, start), "status": "in_progress",
                  "courses": [{"code": c, "credits": C[c]["credits"]} for c in cur]})
    return record(sid, terms, main_done, {"kind": "transfer", "share": round(f, 2)})


def record(sid: str, terms: list[dict], main_done: int, meta: dict, streak: int = 0) -> dict:
    return {"student_id": sid, "terms": terms, "meta": meta,
            "academic_status": {"cumulative_gpa": cgpa_of(terms), "main_semesters_completed": main_done,
                                "consecutive_warning_semesters": streak}}


def with_grades(passed_grades: dict, current: list[str], kind: str, start: int, main_done: int, sid: str,
                meta: dict, fails=()) -> dict:
    rows = [{"code": c, "credits": C[c]["credits"], "grade": g} for c, g in passed_grades.items()]
    rows += [{"code": c, "credits": C[c]["credits"], "grade": "F"} for c in fails]
    terms = [{"term": "spring", "academic_year": year_of("spring", start - 1), "status": "published", "courses": rows},
             {"term": kind, "academic_year": year_of(kind, start), "status": "in_progress",
              "courses": [{"code": c, "credits": C[c]["credits"]} for c in current]}]
    return record(sid, terms, main_done, meta)


def everything_but(left: set, grade: str = "B") -> dict:
    """Grades for every course except `left` (and enough electives)."""
    out = {}
    for c, x in C.items():
        if c in left:
            continue
        if x["type"] == "elective":
            continue
        out[c] = "P" if x.get("graded", True) is False else grade
    for p in POOLS:
        for c in [c for c in p["courses"] if c not in left][:p["choose"]]:
            out[c] = grade
    return out



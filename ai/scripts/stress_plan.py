"""Stress test of the graduation planner: thousands of student situations, each answer checked independently.

The journeys (simulate_journeys.py) follow 24 hand-made students. This script asks a different question: for
ANY situation a student can be in, is the planner's answer right?

  1. Situations. Students are generated by living random histories (different grade levels, failure rates,
     summers, training timing, part-time loads), plus "transfer" students whose passed courses are a random
     set (equivalences), plus hand-made edge cases (hours just under a project threshold, GPA exactly on a
     band edge, only project 3 left, every course done under 2.00...).
  2. For each situation the planner is asked for every target (4 / 4.5 / 5 years) with and without summer.
  3. Each answer is checked three ways, none of which uses the planner's code:
     - the plan itself: every remaining course once, prerequisites before, each course in a term it runs in,
       hour thresholds, hour caps, summer limit, projects in order and never in summer, graduation term
       inside the target;
     - the verdict: an independent solver (written here from courses.json) decides whether ANY schedule
       reaches the target. "Can't" when the solver finds one is a wrong answer, and so is an "earliest
       graduation" that is not the earliest;
     - consistency: a longer target or allowing summer never makes things worse, and the page's table says
       the same as the plan.
  4. Follow the plan: some students do exactly what the plan says, pass everything, and are asked again
     every term. They should graduate when the plan promised.

Nothing here touches ai/data or the database. Run from the repo root (same seed, same result):
    .venv\\Scripts\\python.exe ai\\scripts\\stress_plan.py [number of random students]
Writes ai/simulation/plan_stress.json and ai/simulation/plan_stress_report.html.
"""


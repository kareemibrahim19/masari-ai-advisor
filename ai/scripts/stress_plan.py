STATUS_RANK = {"feasible": 0, "conditional": 1, "impossible": 2}


def semester_of(pj: dict, row_term: dict | None) -> int | None:
    """Main semester number (from enrollment) a graduation term is in; a summer counts as the main before it."""
    if not row_term:
        return None
    m, kind = pj["main_now"], pj["cur"]["term"]
    year = int(pj["cur"]["academic_year"][:4])
    for t in terms_after(kind, year, pj["main_now"], MAX_MAIN + 4):
        if planner._term_label({"term": t["term"], "academic_year": f"{t['year']}-{t['year'] + 1}"})["ar"] == row_term["ar"]:
            return t["main"] if t["main"] is not None else m
        if t["main"] is not None:
            m = t["main"]
    return None


def check_one(rec: dict, follow: bool) -> dict:
    """Every target with and without summer for one student: the answers and what is wrong with them."""
    sid = rec["student_id"]
    d.students = lambda: {sid: rec}
    pj = projection(rec)
    cap = cap_for(pj["cgpa"], pj["main_now"])
    out = {"sid": sid, "meta": rec["meta"], "main_now": pj["main_now"], "earned": pj["earned"], "cgpa": pj["cgpa"],
           "cap": cap, "current": pj["cur"]["term"], "cells": {}, "problems": [], "notes": []}

    def problem(kind, text, **extra):
        out["problems"].append({"kind": kind, "text": text, **extra})

    times = []
    plans = {}
    for years, last in TARGETS.items():
        for summer in (False, True):
            t0 = time.perf_counter()
            try:
                p = planner.build_graduation_plan(sid, years, summer, with_risk=False)
            except Exception as e:  # noqa: BLE001
                problem("crash", f"الخطة وقعت ({years} سنين، صيفي {summer}): {e!r}", trace=traceback.format_exc()[-800:])
                continue
            times.append(time.perf_counter() - t0)
            plans[(years, summer)] = p
            if not p.get("found"):
                problem("error", f"الخطة رجّعت خطأ ({years} سنين): {p.get('error')}")
                continue
            status = p.get("status") or ("feasible" if p["feasible"] else "impossible")
            grad_sem = semester_of(pj, p.get("graduation_term"))
            rows = p.get("terms") or []
            courses = [c for r in rows for c in r["courses"]]
            out["cells"][f"{years}|{int(summer)}"] = {
                "status": status, "grad": (p.get("graduation_term") or {}).get("ar"), "grad_sem": grad_sem,
                "reason": (p.get("why") or {}).get("code"), "conds": [c["kind"] for c in p.get("conditions", [])],
                "ms": round(1000 * times[-1], 1),
                # What the plan asks of the student and the college.
                "summer_courses": sum(1 for c in courses if c["flag"] == "summer_on_demand"),
                "training_main": sum(1 for c in courses if c["flag"] == "college_request"),
                "grad_request": sum(1 for c in courses if c["flag"] == "graduation_request"),
                "paper_project": sum(1 for c in courses if c.get("paper_registration")),
                "paper_load": sum(1 for r in rows if r.get("paper_load")),
                "council": sum(1 for r in rows if r.get("warning")),
                "grad_under_12": any(r.get("below_minimum_paper") for r in rows),
                "improvement": p.get("improvement") is not None}
            for issue in plan_problems(pj, p, summer, cap):
                problem("invalid_plan", f"{years} سنين، صيفي {'أيوه' if summer else 'لأ'}: {issue}")
            if p.get("improvement") is not None or (not p.get("terms") and p["feasible"]):
                continue  # improvement plans and "graduate at the end of this term" are checked separately
            kind, year = pj["cur"]["term"], int(pj["cur"]["academic_year"][:4])
            as_is = oracle(pj["passed"], pj["earned"], cap, kind, year, pj["main_now"], last, summer)
            if status == "feasible":
                if grad_sem is not None and grad_sem > last:
                    problem("late_feasible", f"قال تقدر في {years} سنين بس التخرج في الترم {grad_sem}")
                if as_is is None:
                    problem("oracle_disagrees", f"قال تقدر في {years} سنين والحل المستقل ملقاش جدول")
                continue
            # Not feasible as things stand: the independent solver must agree ...
            if as_is is not None:
                gap = oracle(pj["passed"], pj["earned"], cap, kind, year, pj["main_now"], last, summer, no_gap=True)
                problem("false_no", f"قال مش ممكن في {years} سنين (صيفي {'أيوه' if summer else 'لأ'}) وفيه جدول بيلحق",
                        why=(p.get("why") or {}).get("ar"), years=years, summer=summer,
                        cause="no_gap" if gap is None else "solver", witness=as_is)
            # ... and each lever the planner offers must work, and a lever it does not offer must not.
            if summer and as_is is None and oracle(pj["passed"], pj["earned"], cap, kind, year, pj["main_now"], last,
                                                   summer, summer_after=True) is not None:
                out["notes"].append({"kind": "summer_after", "years": years})
            if not summer and status == "impossible" and pj["main_now"] < last:
                if oracle(pj["passed"], pj["earned"], cap, kind, year, pj["main_now"], last, True) is not None:
                    problem("missed_route", f"قال مش ممكن في {years} سنين من غير صيفي، ومقالش إن الصيفي بيحلها")
            if status == "impossible":
                e = p.get("earliest_main_semester") or grad_sem
                if e is None:
                    if p.get("graduation_term") is None and oracle_earliest(pj, cap, summer, last + 1, MAX_MAIN):
                        problem("no_plan", f"مرجّعش أي خطة ({years} سنين) وفيه خطة جوه الحد الأقصى")
                    continue
                if e - 1 > max(last, pj["main_now"]) and \
                        oracle(pj["passed"], pj["earned"], cap, kind, year, pj["main_now"], e - 1, summer) is not None:
                    problem("not_earliest", f"قال أقرب تخرج الترم {e} ({years} سنين، صيفي {summer}) وينفع الترم {e - 1}")
                # A fall / spring graduation when the summer before it already works (same rules as the planner:
                # no empty semester, 12 hours in every semester but the last).
                grad = (p.get("graduation_term") or {}).get("ar", "")
                if summer and grad and not grad.startswith("الصيفي") and e - 1 >= pj["main_now"] and \
                        oracle(pj["passed"], pj["earned"], cap, kind, year, pj["main_now"], e - 1, True,
                               summer_after=True, no_gap=True, min12=True) is not None:
                    problem("summer_skipped", f"قال أقرب تخرج {grad} ({years} سنين) وينفع يتخرج في الصيفي اللي قبله")
    # What-if: fail one or two current courses and expect some term GPA (the plan page's inputs).
    rng = random.Random(sid)
    graded = [c["code"] for c in pj["cur"]["courses"] if C[c["code"]].get("graded", True) and C[c["code"]]["credits"]]
    if graded:
        failed = rng.sample(graded, min(len(graded), rng.choice([1, 1, 2])))
        ph = sum(C[c]["credits"] for c in graded if c not in failed)
        nh = sum(C[c]["credits"] for c in graded)
        tg = round(rng.uniform(0, 4.0 * ph / nh), 2) if ph else 0.0
        years, last = rng.choice(list(TARGETS.items()))
        summer = rng.random() < 0.5
        try:
            p = planner.build_graduation_plan(sid, years, summer, failed, tg, with_risk=False)
            wj = projection(rec, failed, tg)
            wcap = cap_for(wj["cgpa"], wj["main_now"])
            out["whatif"] = {"failed": failed, "term_gpa": tg, "years": years, "summer": summer,
                             "status": p.get("status"), "cgpa": wj["cgpa"], "planner_cgpa": (p.get("after_this_term") or {}).get("cumulative_gpa")}
            if not p.get("found"):
                problem("error", f"what-if رجّع خطأ: {p.get('error')}")
            else:
                if abs((p["after_this_term"]["cumulative_gpa"] or 0) - (wj["cgpa"] or 0)) > 0.011:
                    problem("whatif_gpa", f"what-if: المعدل المتوقع {p['after_this_term']['cumulative_gpa']} والمحسوب {wj['cgpa']}")
                if p["after_this_term"]["max_credits"] != wcap:
                    problem("whatif_cap", f"what-if: حد الساعات {p['after_this_term']['max_credits']} والمتوقع {wcap}")
                for issue in plan_problems(wj, p, summer, wcap):
                    problem("invalid_plan", f"what-if ({years} سنين): {issue}")
                if p.get("improvement") is None and p.get("terms"):
                    ok = oracle(wj["passed"], wj["earned"], wcap, wj["cur"]["term"], int(wj["cur"]["academic_year"][:4]),
                                wj["main_now"], last, summer)
                    st_ = p.get("status")
                    if (st_ == "feasible") != (ok is not None) and not (st_ != "feasible" and ok is not None and wj["main_now"] >= last):
                        problem("false_no" if ok is not None else "oracle_disagrees",
                                f"what-if ({years} سنين، صيفي {summer}): مساري قال {st_} والحل المستقل {'لقى' if ok is not None else 'ملقاش'} جدول",
                                cause="whatif")
        except Exception as e:  # noqa: BLE001
            problem("crash", f"what-if وقع: {e!r}", trace=traceback.format_exc()[-800:])
    out["ms"] = round(1000 * max(times), 1) if times else None
    out["ms_total"] = round(1000 * sum(times), 1)

    # Consistency: a longer target or summer never makes things worse.
    cells = out["cells"]
    for summer in (0, 1):
        ranks = [(y, cells.get(f"{y}|{summer}")) for y in TARGETS]
        for (y1, a), (y2, b) in zip(ranks, ranks[1:]):
            if a and b and STATUS_RANK[a["status"]] < STATUS_RANK[b["status"]]:
                problem("monotonic", f"ممكن في {y1} سنين ومش ممكن في {y2} سنين (صيفي {summer})")
    for y in TARGETS:
        a, b = cells.get(f"{y}|0"), cells.get(f"{y}|1")
        if a and b and STATUS_RANK[b["status"]] > STATUS_RANK[a["status"]]:
            problem("summer_worse", f"الصيفي خلّى هدف {y} سنين أصعب")
        if a and b and a["grad_sem"] and b["grad_sem"] and b["grad_sem"] > a["grad_sem"] and a["status"] == b["status"] == "impossible":
            problem("summer_worse", f"الصيفي أخّر أقرب تخرج ({y} سنين)")
    # The page's table must say what the plan says.
    try:
        opts = planner.plan_options(sid)
        for o in opts.get("options", []):
            for key, s in (("without_summer", 0), ("with_summer", 1)):
                cell = cells.get(f"{o['target_years']}|{s}")
                if cell and (o[key]["status"] != cell["status"] or (o[key]["graduation_term"] or {}).get("ar") != cell["grad"]):
                    problem("table", f"جدول الأهداف ({o['target_years']}، صيفي {s}) مختلف عن الخطة")
    except Exception as e:  # noqa: BLE001
        problem("crash", f"جدول الأهداف وقع: {e!r}")

    # GPA under 2.00: the plan should not promise graduation without saying the GPA has to come up.
    if pj["cgpa"] is not None and pj["cgpa"] < 2.0:
        p = plans.get((5, True))
        if p and p.get("found") and p.get("graduation_term") and not p.get("improvement"):
            out["notes"].append({"kind": "gpa_under_2", "explanation": p.get("explanation")})
    if follow:
        out["follow"] = follow_plan(rec, pj)
    return out


# ================================================================ following the plan term by term

BAND_GRADE = [(3.0, "A"), (2.0, "B-"), (0.0, "D+")]  # a grade that keeps the GPA inside its band


def follow_plan(rec: dict, pj: dict) -> dict:
    """The student does what the 5-year plan (with summer) says, passes everything with a grade that keeps the
    GPA in its band, and asks again each term. Graduates when promised?"""
    rec = json.loads(json.dumps(rec))
    sid = rec["student_id"]
    cg = pj["cgpa"] if pj["cgpa"] is not None else 2.5
    grade = next(g for lo, g in BAND_GRADE if cg >= lo)
    log, promised = [], None
    for _ in range(30):
        d.students = lambda: {sid: rec}
        p = planner.build_graduation_plan(sid, 5, True, with_risk=False)
        if not p.get("found"):
            return {"ok": False, "why": f"خطأ: {p.get('error')}", "log": log}
        g = (p.get("graduation_term") or {}).get("ar")
        if p.get("improvement") is not None:
            return {"ok": None, "why": "خلّص المواد ومعدله تحت 2.00، فالخطة بقت خطة تحسين", "promised": promised,
                    "gpa": rec["academic_status"]["cumulative_gpa"], "log": log}
        if promised is None and p.get("status") != "conditional":
            promised = g
        elif promised is not None and g and _order(g) > _order(promised):
            return {"ok": False, "why": f"الوعد اتأخر من {promised} لـ {g} وهو ماشي على الخطة بالظبط ونجح في كل حاجة",
                    "promised": promised, "log": log + [g]}
        log.append(g)
        cur = next(t for t in rec["terms"] if t["status"] == "in_progress")
        for c in cur["courses"]:
            c["grade"] = "P" if C[c["code"]].get("graded", True) is False else grade
        cur["status"] = "published"
        if cur["term"] != "summer":
            rec["academic_status"]["main_semesters_completed"] += 1
        rec["academic_status"]["cumulative_gpa"] = cgpa_of(rec["terms"])
        done_now = planner._term_label(cur)["ar"]
        req, pools = remaining({c for c, a in best_attempts(rec["terms"]).items() if is_pass(a["grade"])})
        if not req and not pools:
            gpa = rec["academic_status"]["cumulative_gpa"]
            later = promised is not None and _order(done_now) > _order(promised)
            if gpa < 2.0:
                return {"ok": None, "why": "خلّص المواد ومعدله تحت 2.00", "promised": promised, "graduated": done_now,
                        "gpa": gpa, "log": log}
            return {"ok": not later, "promised": promised, "graduated": done_now, "gpa": gpa,
                    "why": f"خلّص في {done_now} والخطة كانت قايلة {promised}" if later else None, "log": log}
        if not p.get("terms"):
            return {"ok": None, "why": "مفيش خطة تخرج جوه الحد الأقصى للدراسة", "promised": promised, "log": log}
        # The first term of the plan with courses (an empty summer is skipped; an empty main term is waited out).
        nxt = next(r for r in p["terms"] if r["courses"] or r["term"] != "summer")
        rec["terms"].append({"term": nxt["term"], "academic_year": nxt["academic_year"], "status": "in_progress",
                             "courses": [{"code": c["code"], "credits": C[c["code"]]["credits"]} for c in nxt["courses"]]})
    return {"ok": False, "why": "مخلصش بعد 30 ترم", "promised": promised, "log": log}


def _order(label: str | None) -> tuple:
    if not label:
        return (9999, 9)
    word, years = label.split(" ", 1)
    start = int(years[:4])
    return (start, {"الخريف": 0, "الربيع": 1, "الصيفي": 2}[word])



def work(args):
    rec, follow = args
    try:
        return check_one(rec, follow)
    except Exception as e:  # noqa: BLE001
        return {"sid": rec["student_id"], "meta": rec["meta"], "cells": {}, "notes": [],
                "problems": [{"kind": "crash", "text": f"الاختبار وقع: {e!r}", "trace": traceback.format_exc()[-1500:]}]}


def build_students(n: int) -> list[dict]:
    rng = random.Random("masari-stress")
    out = edge_cases()
    i = 0
    while len(out) < n + len(edge_cases()):
        i += 1
        maker = transfer if rng.random() < 0.2 else lived
        s = maker(rng, f"ST-{i:05d}")
        if s:
            out.append(s)
    return out


def kept(results: list[dict], students: list[dict]) -> list[dict]:
    """Full records only of the students something went wrong for (the rest come back with the same seed)."""
    keep = {r["sid"] for r in results if r["problems"] or (r.get("follow") or {}).get("ok") is False}
    for r in results:
        for n in r.get("notes", []):
            n.pop("said", None)
    for r in results:
        if r.get("follow"):
            r["follow"].pop("log", None)
        if r.get("deviate"):
            r["deviate"].pop("log", None)
    return [s for s in students if s["student_id"] in keep]


def examples(k: int = 3) -> None:
    """Students who do not follow the plan, term by term, for people to read: what Masari said, what the student
    registered instead, and the plan after. Picks the ones who changed the most and still graduated."""
    found = []
    for s in build_students(120):
        if s["meta"]["kind"] != "lived" or s["academic_status"]["main_semesters_completed"] > 6:
            continue
        r = deviate_plan(s, projection(s))
        kinds = {c for e in r["log"] for c in e["changes"]} | {g for e in r["log"] for g in e["results"].values()
                                                              if g in (WITHDRAWN, DEPRIVED, "F")}
        if r["outcome"] == "اتخرج" and not r["issues"]:
            found.append((len(kinds), r["steps"], s["student_id"], s["meta"], r))
    found.sort(key=lambda x: (-x[0], -x[1]))
    out = [{"sid": sid, "meta": meta, **r} for _, _, sid, meta, r in found[:k]]
    for e in out:
        for step in e["log"]:
            step["results"] = {f"{c} {C[c]['name_ar']}": g for c, g in step["results"].items()}
    (OUT / "plan_stress_examples.json").write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    print("examples:", [(e["sid"], e["steps"]) for e in out])


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    if sys.argv[1:] == ["--examples"]:
        examples()
        return
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 1500
    students = build_students(n)
    # One student in four follows the plan to the end, one in eight does their own thing, one in eight follows it
    # while the GPA goes up and down; edge cases follow.
    jobs = [(s, "follow" if i % 4 == 0 or s["meta"]["kind"] == "edge" else "deviate" if i % 8 == 1
             else "gpa" if i % 8 == 2 else None)
            for i, s in enumerate(students)]
    t0 = time.time()
    results = []
    with Pool(max(1, min(6, (os.cpu_count() or 2) - 2))) as pool:
        for k, r in enumerate(pool.imap_unordered(work, jobs, chunksize=2), 1):
            results.append(r)
            if k % 100 == 0:
                bad = sum(1 for x in results if x["problems"])
                print(f"{k}/{len(jobs)}  {time.time() - t0:.0f}s  students with problems: {bad}", flush=True)
    results.sort(key=lambda r: r["sid"])
    meta = {"students": len(results), "seconds": round(time.time() - t0), "seed": "masari-stress",
            "by_kind": Counter(r["meta"]["kind"] for r in results)}
    OUT.mkdir(exist_ok=True)
    (OUT / "plan_stress.json").write_text(json.dumps({"meta": meta, "results": results, "students": kept(results, students)},
                                                     ensure_ascii=False, default=list), encoding="utf-8")
    kinds = Counter(p["kind"] for r in results for p in r["problems"])
    print(json.dumps({"students": len(results), "problems": kinds}, ensure_ascii=False))


if __name__ == "__main__":
    main()

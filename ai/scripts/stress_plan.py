STATUS_RANK = {"feasible": 0, "conditional": 1, "impossible": 2}


def semester_of(pj: dict, row_term: dict | None) -> int | None:
    """Main semester number (from enrollment) a graduation term is in; a summer counts as the main before it."""
    if not row_term:
        return None
    m, kind = pj["main_now"], pj["cur"]["term"]
    year = int(pj["cur"]["academic_year"][:4])
    for t in terms_after(kind, year, pj["main_now"], MAX_MAIN + 4):
        if planner._term_label({"term": t["term"], "academic_year": f"{t['year']}-{t['year'] + 1}"})["ar"] == row_term["ar"]:
            return t["main"] if t["main"] is not None else m
        if t["main"] is not None:
            m = t["main"]
    return None


def check_one(rec: dict, follow: bool) -> dict:
    """Every target with and without summer for one student: the answers and what is wrong with them."""
    sid = rec["student_id"]
    d.students = lambda: {sid: rec}
    pj = projection(rec)
    cap = cap_for(pj["cgpa"], pj["main_now"])
    out = {"sid": sid, "meta": rec["meta"], "main_now": pj["main_now"], "earned": pj["earned"], "cgpa": pj["cgpa"],
           "cap": cap, "current": pj["cur"]["term"], "cells": {}, "problems": [], "notes": []}

    def problem(kind, text, **extra):
        out["problems"].append({"kind": kind, "text": text, **extra})

    times = []
    plans = {}
    for years, last in TARGETS.items():
        for summer in (False, True):
            t0 = time.perf_counter()
            try:
                p = planner.build_graduation_plan(sid, years, summer, with_risk=False)
            except Exception as e:  # noqa: BLE001
                problem("crash", f"الخطة وقعت ({years} سنين، صيفي {summer}): {e!r}", trace=traceback.format_exc()[-800:])
                continue
            times.append(time.perf_counter() - t0)
            plans[(years, summer)] = p
            if not p.get("found"):
                problem("error", f"الخطة رجّعت خطأ ({years} سنين): {p.get('error')}")
                continue
            status = p.get("status") or ("feasible" if p["feasible"] else "impossible")
            grad_sem = semester_of(pj, p.get("graduation_term"))
            rows = p.get("terms") or []
            courses = [c for r in rows for c in r["courses"]]
            out["cells"][f"{years}|{int(summer)}"] = {
                "status": status, "grad": (p.get("graduation_term") or {}).get("ar"), "grad_sem": grad_sem,
                "reason": (p.get("why") or {}).get("code"), "conds": [c["kind"] for c in p.get("conditions", [])],
                "ms": round(1000 * times[-1], 1),
                # What the plan asks of the student and the college.
                "summer_courses": sum(1 for c in courses if c["flag"] == "summer_on_demand"),
                "training_main": sum(1 for c in courses if c["flag"] == "college_request"),
                "grad_request": sum(1 for c in courses if c["flag"] == "graduation_request"),
                "open_request": sum(1 for c in courses if c["flag"] == "open_request"),
                "paper_project": sum(1 for c in courses if c.get("paper_registration") and c.get("hours_needed")),
                "paper_load": sum(1 for r in rows if r.get("paper_load")),
                "council": sum(1 for r in rows if r.get("warning")),
                "grad_under_12": any(r.get("below_minimum_paper") for r in rows),
                "improvement": p.get("improvement") is not None}
            for issue in plan_problems(pj, p, summer, cap):
                problem("invalid_plan", f"{years} سنين، صيفي {'أيوه' if summer else 'لأ'}: {issue}")
            if p.get("improvement") is not None:
                continue  # improvement plans are checked by plan_problems
            if not p.get("terms") and p.get("graduation_term"):  # graduates at the end of this term
                if (status == "feasible") != (pj["main_now"] <= last):
                    problem("graduate_now", f"بيتخرج آخر الترم ده (الترم {pj['main_now']}) ومساري قال {status} لهدف {years} سنين")
                continue
            kind, year = pj["cur"]["term"], int(pj["cur"]["academic_year"][:4])
            as_is = oracle(pj["passed"], pj["earned"], cap, kind, year, pj["main_now"], last, summer)
            if status == "feasible":
                if grad_sem is not None and grad_sem > last:
                    problem("late_feasible", f"قال تقدر في {years} سنين بس التخرج في الترم {grad_sem}")
                if as_is is None:
                    problem("oracle_disagrees", f"قال تقدر في {years} سنين والحل المستقل ملقاش جدول")
                continue
            # Not feasible as things stand: the independent solver must agree ...
            if as_is is not None:
                problem("false_no", f"قال مش ممكن في {years} سنين (صيفي {'أيوه' if summer else 'لأ'}) وفيه جدول بيلحق",
                        why=(p.get("why") or {}).get("ar"), years=years, summer=summer, witness=as_is)
            # ... summer is offered when it is what makes the target ...
            if not summer and status == "impossible" and \
                    oracle(pj["passed"], pj["earned"], cap, kind, year, pj["main_now"], last, True) is not None:
                problem("missed_route", f"قال مش ممكن في {years} سنين من غير صيفي، ومقالش إن الصيفي بيحلها")
            if status != "impossible":
                continue
            # ... and "earliest graduation" is the earliest term: nothing finishes a term before it.
            grad = p.get("graduation_term")
            if not grad:
                if oracle_earliest(pj, cap, summer, last + 1, MAX_MAIN) is not None:
                    problem("no_plan", f"مرجّعش أي خطة ({years} سنين) وفيه خطة جوه الحد الأقصى")
                continue
            last_row = (p.get("terms") or [{}])[-1]
            if grad["ar"].startswith("الصيفي") and not any(c["flag"] == "summer_on_demand" for c in last_row.get("courses", [])):
                earlier = None  # only the training in the last summer: the usual path, not a later graduation
            elif grad["ar"].startswith("الصيفي"):  # could it end with the main semester before this summer?
                earlier = oracle(pj["passed"], pj["earned"], cap, kind, year, pj["main_now"], grad_sem, summer,
                                 summer_after=False)
            else:  # could it end by the summer before this semester (or the semester before)?
                earlier = (oracle(pj["passed"], pj["earned"], cap, kind, year, pj["main_now"], grad_sem - 1, summer)
                           if grad_sem - 1 >= pj["main_now"] else None)
            if earlier is not None:
                problem("not_earliest", f"قال أقرب تخرج {grad['ar']} ({years} سنين، صيفي {summer}) وفيه ترم قبله بيلحق",
                        witness=earlier)
    # What-if: fail one or two current courses and expect some term GPA (the plan page's inputs).
    rng = random.Random(sid)
    graded = [c["code"] for c in pj["cur"]["courses"] if C[c["code"]].get("graded", True) and C[c["code"]]["credits"]]
    if graded:
        failed = rng.sample(graded, min(len(graded), rng.choice([1, 1, 2])))
        ph = sum(C[c]["credits"] for c in graded if c not in failed)
        nh = sum(C[c]["credits"] for c in graded)
        tg = math.floor(100 * rng.uniform(0, 4.0 * ph / nh)) / 100 if ph else 0.0  # at most the highest possible
        years, last = rng.choice(list(TARGETS.items()))
        summer = rng.random() < 0.5
        try:
            p = planner.build_graduation_plan(sid, years, summer, failed, tg, with_risk=False)
            wj = projection(rec, failed, tg)
            wcap = cap_for(wj["cgpa"], wj["main_now"])
            out["whatif"] = {"failed": failed, "term_gpa": tg, "years": years, "summer": summer,
                             "status": p.get("status"), "cgpa": wj["cgpa"], "planner_cgpa": (p.get("after_this_term") or {}).get("cumulative_gpa")}
            if not p.get("found"):
                problem("error", f"what-if رجّع خطأ: {p.get('error')}")
            else:
                if abs((p["after_this_term"]["cumulative_gpa"] or 0) - (wj["cgpa"] or 0)) > 0.011:
                    problem("whatif_gpa", f"what-if: المعدل المتوقع {p['after_this_term']['cumulative_gpa']} والمحسوب {wj['cgpa']}")
                if p["after_this_term"]["max_credits"] != wcap:
                    problem("whatif_cap", f"what-if: حد الساعات {p['after_this_term']['max_credits']} والمتوقع {wcap}")
                for issue in plan_problems(wj, p, summer, wcap):
                    problem("invalid_plan", f"what-if ({years} سنين): {issue}")
                if p.get("improvement") is None and p.get("terms"):
                    ok = oracle(wj["passed"], wj["earned"], wcap, wj["cur"]["term"], int(wj["cur"]["academic_year"][:4]),
                                wj["main_now"], last, summer)
                    st_ = p.get("status")
                    if (st_ == "feasible") != (ok is not None):
                        problem("false_no" if ok is not None else "oracle_disagrees",
                                f"what-if ({years} سنين، صيفي {summer}): مساري قال {st_} والحل المستقل {'لقى' if ok is not None else 'ملقاش'} جدول",
                                cause="whatif")
        except Exception as e:  # noqa: BLE001
            problem("crash", f"what-if وقع: {e!r}", trace=traceback.format_exc()[-800:])
    out["ms"] = round(1000 * max(times), 1) if times else None
    out["ms_total"] = round(1000 * sum(times), 1)

    # Frozen right now: the plan says so (student affairs, fees) and starts with the semester they return.
    if pj["cur"]["status"] == "frozen":
        for key, pl in plans.items():
            if pl.get("found") and pl.get("terms") and not ("شئون الطلاب" in pl.get("explanation", "") and pl.get("frozen")):
                problem("frozen", f"موقف قيده والخطة ({key[0]} سنين) مقالتش ده أو مقالتش يطلبه منين")
    # Consistency: a longer target or summer never makes things worse.
    cells = out["cells"]
    for summer in (0, 1):
        ranks = [(y, cells.get(f"{y}|{summer}")) for y in TARGETS]
        for (y1, a), (y2, b) in zip(ranks, ranks[1:]):
            if a and b and STATUS_RANK[a["status"]] < STATUS_RANK[b["status"]]:
                problem("monotonic", f"ممكن في {y1} سنين ومش ممكن في {y2} سنين (صيفي {summer})")
    for y in TARGETS:
        a, b = cells.get(f"{y}|0"), cells.get(f"{y}|1")
        if a and b and STATUS_RANK[b["status"]] > STATUS_RANK[a["status"]]:
            problem("summer_worse", f"الصيفي خلّى هدف {y} سنين أصعب")
        if a and b and a["grad_sem"] and b["grad_sem"] and b["grad_sem"] > a["grad_sem"] and a["status"] == b["status"] == "impossible":
            problem("summer_worse", f"الصيفي أخّر أقرب تخرج ({y} سنين)")
    # The page's table must say what the plan says.
    try:
        opts = planner.plan_options(sid)
        for o in opts.get("options", []):
            for key, s in (("without_summer", 0), ("with_summer", 1)):
                cell = cells.get(f"{o['target_years']}|{s}")
                if cell and (o[key]["status"] != cell["status"] or (o[key]["graduation_term"] or {}).get("ar") != cell["grad"]):
                    problem("table", f"جدول الأهداف ({o['target_years']}، صيفي {s}) مختلف عن الخطة")
    except Exception as e:  # noqa: BLE001
        problem("crash", f"جدول الأهداف وقع: {e!r}")

    # GPA under 2.00: the plan says graduation needs 2.00, how many semesters are left before dismissal (article 25)
    # and the semester GPA that gets back to 2.00.
    if pj["cgpa"] is not None and pj["cgpa"] < 2.0:
        p = plans.get((5, True))
        if p and p.get("found") and p.get("graduation_term") and p.get("improvement") is None:
            w = p.get("gpa_warning")
            streak = rec["academic_status"].get("consecutive_warning_semesters") or 0
            if pj["cur"]["term"] != "summer" and pj["cur"]["status"] != "frozen":  # a frozen term changes nothing
                streak = streak + 1 if pj["main_now"] >= R["warning_starts_after_main_semester"] else 0
            left = max(0, R["dismissal_after_consecutive_low_semesters"] - streak)
            out["notes"].append({"kind": "gpa_under_2", "left": left, "said": w})
            if not w:
                problem("gpa_warning", "معدله تحت 2.00 والخطة مقالتش إن التخرج محتاج 2.00 ولا إمتى الفصل")
            else:
                if w["semesters_left"] != left:
                    problem("gpa_warning", f"قال فاضل {w['semesters_left']} ترم قبل الفصل والمتوقع {left}")
                if left:
                    need = math.ceil((2.0 * (pj["graded"] + cap) - pj["points"]) / cap * 100 - 1e-9) / 100
                    if abs((w.get("next_term_gpa") or -9) - need) > 0.011:
                        problem("gpa_warning", f"قال محتاج معدل ترم {w.get('next_term_gpa')} والمحسوب {need}")
    if follow and pj["cur"]["status"] == "frozen":  # frozen now: comes back the way Masari says, then goes on
        rec, pj = returned(rec)
        if rec is None:
            return out
    if follow == "follow":
        out["follow"] = follow_plan(rec, pj)
    elif follow == "gpa":
        out["gpa_path"] = gpa_path(rec, pj)
        for issue in out["gpa_path"]["issues"]:
            problem("gpa_path", issue)
    elif follow == "deviate":
        out["deviate"] = deviate_plan(rec, pj)
        for issue in out["deviate"]["issues"]:
            problem("deviate", issue)
    return out


# ================================================================ following the plan term by term

BAND_GRADE = [(3.0, "A"), (2.0, "B-"), (0.0, "D+")]  # a grade that keeps the GPA inside its band


def follow_plan(rec: dict, pj: dict) -> dict:
    """The student does what the 5-year plan (with summer) says, passes everything with a grade that keeps the
    GPA in its band, and asks again each term. Graduates when promised?"""
    rec = json.loads(json.dumps(rec))
    sid = rec["student_id"]
    cg = pj["cgpa"] if pj["cgpa"] is not None else 2.5
    grade = next(g for lo, g in BAND_GRADE if cg >= lo)
    log, promised = [], None
    for _ in range(30):
        d.students = lambda: {sid: rec}
        p = planner.build_graduation_plan(sid, 5, True, with_risk=False)
        if not p.get("found"):
            return {"ok": False, "why": f"خطأ: {p.get('error')}", "log": log}
        g = (p.get("graduation_term") or {}).get("ar")
        if p.get("improvement") is not None:
            return {"ok": None, "why": "خلّص المواد ومعدله تحت 2.00، فالخطة بقت خطة تحسين", "promised": promised,
                    "gpa": rec["academic_status"]["cumulative_gpa"], "log": log}
        if promised is None and p.get("status") != "conditional":
            promised = g
        elif promised is not None and g and _order(g) > _order(promised):
            return {"ok": False, "why": f"الوعد اتأخر من {promised} لـ {g} وهو ماشي على الخطة بالظبط ونجح في كل حاجة",
                    "promised": promised, "log": log + [g]}
        log.append(g)
        cur = next(t for t in rec["terms"] if t["status"] == "in_progress")
        for c in cur["courses"]:
            c["grade"] = "P" if C[c["code"]].get("graded", True) is False else grade
        cur["status"] = "published"
        if cur["term"] != "summer":
            rec["academic_status"]["main_semesters_completed"] += 1
        rec["academic_status"]["cumulative_gpa"] = cgpa_of(rec["terms"])
        done_now = planner._term_label(cur)["ar"]
        req, pools = remaining({c for c, a in best_attempts(rec["terms"]).items() if is_pass(a["grade"])})
        if not req and not pools:
            gpa = rec["academic_status"]["cumulative_gpa"]
            later = promised is not None and _order(done_now) > _order(promised)
            if gpa < 2.0:
                return {"ok": None, "why": "خلّص المواد ومعدله تحت 2.00", "promised": promised, "graduated": done_now,
                        "gpa": gpa, "log": log}
            return {"ok": not later, "promised": promised, "graduated": done_now, "gpa": gpa,
                    "why": f"خلّص في {done_now} والخطة كانت قايلة {promised}" if later else None, "log": log}
        if not p.get("terms"):
            return {"ok": None, "why": "مفيش خطة تخرج جوه الحد الأقصى للدراسة", "promised": promised, "log": log}
        # The first term of the plan with courses (an empty summer is skipped; an empty main term is waited out).
        nxt = next(r for r in p["terms"] if r["courses"] or r["term"] != "summer")
        rec["terms"].append({"term": nxt["term"], "academic_year": nxt["academic_year"], "status": "in_progress",
                             "courses": [{"code": c["code"], "credits": C[c["code"]]["credits"]} for c in nxt["courses"]]})
    return {"ok": False, "why": "مخلصش بعد 30 ترم", "promised": promised, "log": log}


def returned(rec: dict):
    """A student frozen now registers the semester they return in, as the plan says (None if there is no plan)."""
    rec = json.loads(json.dumps(rec))
    sid = rec["student_id"]
    d.students = lambda: {sid: rec}
    p = planner.build_graduation_plan(sid, 5, True, with_risk=False)
    back = [r for r in (p.get("terms") or [])[1:] if r["courses"]]
    if not back:
        return None, None
    rec["terms"].append({"term": back[0]["term"], "academic_year": back[0]["academic_year"], "status": "in_progress",
                         "courses": [{"code": c["code"], "credits": C[c["code"]]["credits"]} for c in back[0]["courses"]]})
    return rec, projection(rec)


def deviate_plan(rec: dict, pj: dict) -> dict:
    """A student who asks Masari every term but does not do exactly what it says: drops courses, adds others,
    skips a summer, freezes a semester, withdraws (W), fails (F) or is deprived (DN). Every term Masari must re-plan
    from what was really registered: a plan that can be followed, and the right verdict."""
    rec = json.loads(json.dumps(rec))
    sid = rec["student_id"]
    rng = random.Random("deviate-" + sid)
    issues, steps, did, log = [], 0, Counter(), []
    cg = pj["cgpa"] if pj["cgpa"] is not None else 2.5
    grade = next(g for lo, g in BAND_GRADE if cg >= lo)
    outcome = "30 ترم من غير ما يخلّص"
    for steps in range(1, 31):
        d.students = lambda: {sid: rec}
        cj = projection(rec)
        cap = cap_for(cj["cgpa"], cj["main_now"])
        try:
            p = planner.build_graduation_plan(sid, 5, True, with_risk=False)
        except Exception as e:  # noqa: BLE001
            issues.append(f"ترم {steps}: الخطة وقعت {e!r}")
            outcome = "الخطة وقعت"
            break
        if not p.get("found"):
            issues.append(f"ترم {steps}: الخطة رجّعت خطأ: {p.get('error')}")
            outcome = "خطأ"
            break
        for issue in plan_problems(cj, p, True, cap):
            issues.append(f"ترم {steps}: {issue}")
        if p.get("improvement") is None and p.get("terms"):
            ok = oracle(cj["passed"], cj["earned"], cap, cj["cur"]["term"], int(cj["cur"]["academic_year"][:4]),
                        cj["main_now"], TARGETS[5], True)
            if (p.get("status") == "feasible") != (ok is not None):
                issues.append(f"ترم {steps}: مساري قال {p.get('status')} والحل المستقل {'لقى' if ok else 'ملقاش'} جدول")
        # The term is graded: mostly as the student's level, sometimes not.
        cur = next(t for t in rec["terms"] if t["status"] == "in_progress")
        results = {}
        for c in cur["courses"]:
            r = rng.random()
            if C[c["code"]].get("graded", True) is False:
                results[c["code"]] = "FP" if r < 0.05 else "P"
            else:
                results[c["code"]] = WITHDRAWN if r < 0.05 else "F" if r < 0.12 else DEPRIVED if r < 0.14 else grade
            did[results[c["code"]]] += results[c["code"]] in (WITHDRAWN, "F", DEPRIVED, "FP")
        # Masari after the results (asked as a what-if while the term is still in progress, like the page does).
        failed = [c for c, g in results.items() if not is_pass(g)]
        graded = [c["code"] for c in cur["courses"] if C[c["code"]].get("graded", True) and C[c["code"]]["credits"]]
        hrs = sum(C[c]["credits"] for c in graded)
        pts = sum(GP.get(results[c], 0) * C[c]["credits"] for c in graded)
        tg = math.floor(100 * pts / hrs) / 100 if hrs else None
        try:
            p2 = planner.build_graduation_plan(sid, 5, True, failed, tg, with_risk=False)
        except Exception as e:  # noqa: BLE001
            issues.append(f"ترم {steps}: الخطة بعد النتيجة وقعت {e!r}")
            outcome = "الخطة وقعت"
            break
        for c in cur["courses"]:
            c["grade"] = results[c["code"]]
        cur["status"] = "published"
        st = rec["academic_status"]
        st["cumulative_gpa"] = cgpa_of(rec["terms"])
        if cur["term"] != "summer":
            st["main_semesters_completed"] += 1
            low = st["cumulative_gpa"] is not None and st["cumulative_gpa"] < 2
            st["consecutive_warning_semesters"] = (st.get("consecutive_warning_semesters", 0) + 1
                                                   if low and st["main_semesters_completed"] >= 2 else 0)
            if st["consecutive_warning_semesters"] >= R["dismissal_after_consecutive_low_semesters"]:
                outcome = "وصل لحد الفصل (3 ترمات إنذار)"
                break
        passed = {c for c, a in best_attempts(rec["terms"]).items() if is_pass(a["grade"])}
        req, pools = remaining(passed)
        if not req and not pools:
            outcome = "اتخرج" if st["cumulative_gpa"] >= 2 else "خلّص المواد ومعدله تحت 2.00"
            break
        if not p2.get("found"):
            issues.append(f"ترم {steps}: الخطة بعد النتيجة رجّعت خطأ: {p2.get('error')}")
            outcome = "خطأ"
            break
        if p2.get("improvement") is not None:
            outcome = "خلّص المواد ومعدله تحت 2.00 (خطة تحسين)"
            break
        # Next term: the plan's next term, changed the way students change it.
        rows = [r for r in p2.get("terms") or [] if r["courses"] or r["term"] != "summer"]
        if not rows:
            outcome = "مفيش خطة جوه الحد الأقصى للدراسة"
            break
        nxt = rows[0]
        before = dict(did)
        entry = {"term": when_label(cur["term"], cur["academic_year"]),
                 "results": {c["code"]: c["grade"] for c in cur["courses"]},
                 "grad_before": (p.get("graduation_term") or {}).get("ar"),
                 "grad_after": (p2.get("graduation_term") or {}).get("ar"),
                 "said": {"term": when_label(nxt["term"], nxt["academic_year"]), "courses": [c["code"] for c in nxt["courses"]]}}
        if nxt["term"] == "summer" and len(rows) > 1 and rng.random() < 0.3:
            nxt = rows[1]  # skips the summer
            did["skipped_summer"] += 1
        term, year = nxt["term"], int(nxt["academic_year"][:4])
        codes = [c["code"] for c in nxt["courses"]]
        if term != "summer" and rng.random() < 0.04:  # freezes the semester, then asks Masari on the way back
            did["freeze"] += 1
            rec["terms"].append({"term": term, "academic_year": year_of(term, year), "status": "frozen", "courses": []})
            d.students = lambda: {sid: rec}
            fj = projection(rec)
            fcap = cap_for(fj["cgpa"], fj["main_now"])
            pf = planner.build_graduation_plan(sid, 5, True, with_risk=False)
            if not pf.get("found"):
                issues.append(f"ترم {steps}: موقف قيده والخطة رجّعت خطأ: {pf.get('error')}")
                outcome = "خطأ"
                break
            for issue in plan_problems(fj, pf, True, fcap):
                issues.append(f"ترم {steps} (وقف قيد): {issue}")
            back = [r for r in (pf.get("terms") or [])[1:] if r["courses"] or r["term"] != "summer"]
            if not back:
                outcome = "مفيش خطة بعد وقف القيد"
                break
            entry["frozen"] = when_label(term, year_of(term, year))
            entry["said"] = {"term": when_label(back[0]["term"], back[0]["academic_year"]),
                             "courses": [c["code"] for c in back[0]["courses"]]}
            term, year = back[0]["term"], int(back[0]["academic_year"][:4])
            codes = [c["code"] for c in back[0]["courses"]]
        if term != "summer":
            if codes and rng.random() < 0.3:
                for c in rng.sample(codes, min(len(codes) - 1, rng.choice([1, 2]))):
                    codes.remove(c)
                did["dropped"] += 1
            if rng.random() < 0.3 or not codes:
                earned = sum(C[c]["credits"] for c in passed)
                extra = [c for c in pick(rng, rec["terms"], passed, earned, term, st["cumulative_gpa"],
                                         st["main_semesters_completed"], "average", False) if c not in codes]
                load = sum(C[c]["credits"] for c in codes)
                for c in extra:
                    if load + C[c]["credits"] <= cap and not (C[c]["type"] == "project" and any(x in PROJECTS for x in codes)):
                        codes.append(c)
                        load += C[c]["credits"]
                        did["added"] += 1
                        if not codes or rng.random() < 0.5:
                            break
        # The registration system refuses what the student is not allowed yet (a prerequisite failed, hours short).
        earned = sum(C[c]["credits"] for c in passed)
        codes = [c for c in codes if c not in passed and all(x in passed for x in prereqs(c)) and earned >= hours_least(c)]
        if not codes:  # nothing of the plan is allowed: registers what is open instead
            codes = pick(rng, rec["terms"], passed, earned, term, st["cumulative_gpa"], st["main_semesters_completed"],
                         "average", False)
        if not codes:
            outcome = "مفيش مواد يسجلها"
            break
        rec["terms"].append({"term": term, "academic_year": year_of(term, year), "status": "in_progress",
                             "courses": [{"code": c, "credits": C[c]["credits"]} for c in codes]})
        entry["registered"] = {"term": when_label(term, year_of(term, year)), "courses": codes}
        entry["changes"] = [k for k in ("skipped_summer", "freeze", "dropped", "added") if did[k] > before.get(k, 0)]
        log.append(entry)
    return {"steps": steps, "issues": issues, "outcome": outcome, "did": dict(did), "log": log}


def when_label(term: str, academic_year: str) -> str:
    """'fall', '2029-2030' -> 'خريف 2029' (the calendar year the term falls in)."""
    start = int(academic_year[:4])
    return f"{ {'fall': 'خريف', 'spring': 'ربيع', 'summer': 'صيفي'}[term]} {start if term == 'fall' else start + 1}"


# Term grades over time: the GPA goes up, down, or back and forth across 2.00 and 3.00 (the cap and the warning move).
GPA_PATHS = {
    "rising": ["D", "D+", "C", "C+", "B", "B+", "A", "A"],
    "falling": ["A", "B+", "B-", "C", "C-", "D+", "D", "D"],
    "around_2": ["D+", "B", "D+", "B-", "D", "B", "C-", "B"],
    "around_3": ["B-", "A-", "B-", "A", "C+", "A", "B", "A-"],
    "crash_recover": ["D", "D", "D+", "A", "A", "A-", "A", "A"],
}


def gpa_path(rec: dict, pj: dict) -> dict:
    """The student follows the plan and passes, but the GPA moves term by term along a path. Every term Masari is
    asked again: the hour cap must follow the new GPA (and academic warning), the plan must still be valid and its
    verdict right, and under 2.00 the warning must say how many semesters are left and the GPA needed."""
    rec = json.loads(json.dumps(rec))
    sid = rec["student_id"]
    name = list(GPA_PATHS)[sum(map(ord, sid)) % len(GPA_PATHS)]
    path = GPA_PATHS[name]
    issues, log = [], []
    outcome, steps, mains = "30 ترم من غير ما يخلّص", 0, 0
    for steps in range(1, 31):
        d.students = lambda: {sid: rec}
        cj = projection(rec)
        cap = cap_for(cj["cgpa"], cj["main_now"])
        try:
            p = planner.build_graduation_plan(sid, 5, True, with_risk=False)
        except Exception as e:  # noqa: BLE001
            issues.append(f"ترم {steps}: الخطة وقعت {e!r}")
            outcome = "الخطة وقعت"
            break
        if not p.get("found"):
            issues.append(f"ترم {steps}: خطأ: {p.get('error')}")
            outcome = "خطأ"
            break
        said_cap = p["after_this_term"]["max_credits"]
        if said_cap != cap:
            issues.append(f"ترم {steps}: معدله هيبقى {cj['cgpa']} وحد الساعات اللي مساري قاله {said_cap} والمتوقع {cap}")
        for issue in plan_problems(cj, p, True, cap):
            issues.append(f"ترم {steps}: {issue}")
        if p.get("improvement") is None and p.get("terms"):
            ok = oracle(cj["passed"], cj["earned"], cap, cj["cur"]["term"], int(cj["cur"]["academic_year"][:4]),
                        cj["main_now"], TARGETS[5], True)
            if (p.get("status") == "feasible") != (ok is not None):
                issues.append(f"ترم {steps}: مساري قال {p.get('status')} والحل المستقل {'لقى' if ok else 'ملقاش'} جدول")
        w = p.get("gpa_warning")
        low = cj["cgpa"] is not None and cj["cgpa"] < 2
        if low and p.get("graduation_term") and p.get("improvement") is None:
            streak = rec["academic_status"].get("consecutive_warning_semesters") or 0
            if cj["cur"]["term"] != "summer":
                streak = streak + 1 if cj["main_now"] >= R["warning_starts_after_main_semester"] else 0
            left = max(0, R["dismissal_after_consecutive_low_semesters"] - streak)
            if not w:
                issues.append(f"ترم {steps}: معدله {cj['cgpa']} ومفيش تحذير")
            elif w["semesters_left"] != left:
                issues.append(f"ترم {steps}: قال فاضل {w['semesters_left']} ترم قبل الفصل والمتوقع {left}")
            elif left:
                need = math.ceil((2.0 * (cj["graded"] + cap) - cj["points"]) / cap * 100 - 1e-9) / 100
                if abs((w.get("next_term_gpa") or -9) - need) > 0.011:
                    issues.append(f"ترم {steps}: قال محتاج معدل {w.get('next_term_gpa')} والمحسوب {need}")
        elif not low and w:
            issues.append(f"ترم {steps}: معدله {cj['cgpa']} ومساري حذّره إنه تحت 2.00")
        log.append({"cgpa": cj["cgpa"], "cap": cap, "grad": (p.get("graduation_term") or {}).get("ar"),
                    "warning": bool(w)})
        # Grade the term along the path (main semesters move along it; a summer gets the same grade).
        cur = next(t for t in rec["terms"] if t["status"] == "in_progress")
        g = path[min(mains, len(path) - 1)]
        results = {c["code"]: ("P" if C[c["code"]].get("graded", True) is False else g) for c in cur["courses"]}
        graded = [c["code"] for c in cur["courses"] if C[c["code"]].get("graded", True) and C[c["code"]]["credits"]]
        hrs = sum(C[c]["credits"] for c in graded)
        tg = math.floor(100 * sum(GP[results[c]] * C[c]["credits"] for c in graded) / hrs) / 100 if hrs else None
        p2 = planner.build_graduation_plan(sid, 5, True, [], tg, with_risk=False)  # after the results (what-if)
        for c in cur["courses"]:
            c["grade"] = results[c["code"]]
        cur["status"] = "published"
        st = rec["academic_status"]
        st["cumulative_gpa"] = cgpa_of(rec["terms"])
        if cur["term"] != "summer":
            mains += 1
            st["main_semesters_completed"] += 1
            under = st["cumulative_gpa"] is not None and st["cumulative_gpa"] < 2
            st["consecutive_warning_semesters"] = (st.get("consecutive_warning_semesters", 0) + 1
                                                   if under and st["main_semesters_completed"] >= 2 else 0)
            if st["consecutive_warning_semesters"] >= R["dismissal_after_consecutive_low_semesters"]:
                outcome = "وصل لحد الفصل (3 ترمات إنذار)"
                break
        passed = {c for c, a in best_attempts(rec["terms"]).items() if is_pass(a["grade"])}
        req, pools = remaining(passed)
        if not req and not pools:
            outcome = "اتخرج" if st["cumulative_gpa"] >= 2 else "خلّص المواد ومعدله تحت 2.00"
            break
        if not p2.get("found") or p2.get("improvement") is not None:
            outcome = "خلّص المواد ومعدله تحت 2.00 (خطة تحسين)" if p2.get("improvement") is not None else "خطأ"
            break
        rows = [r for r in p2.get("terms") or [] if r["courses"] or r["term"] != "summer"]
        if not rows:
            outcome = "مفيش خطة جوه الحد الأقصى للدراسة"
            break
        nxt = rows[0]
        earned = sum(C[c]["credits"] for c in passed)
        codes = [c["code"] for c in nxt["courses"] if all(x in passed for x in prereqs(c["code"]))
                 and earned >= hours_least(c["code"])]
        if not codes:
            outcome = "مفيش مواد يسجلها"
            break
        rec["terms"].append({"term": nxt["term"], "academic_year": nxt["academic_year"], "status": "in_progress",
                             "courses": [{"code": c, "credits": C[c]["credits"]} for c in codes]})
    caps = [x["cap"] for x in log]
    return {"path": name, "steps": steps, "issues": issues, "outcome": outcome,
            "cap_changes": sum(1 for a, b in zip(caps, caps[1:]) if a != b),
            "date_changes": sum(1 for a, b in zip(log, log[1:]) if a["grad"] != b["grad"]),
            "warned_terms": sum(1 for x in log if x["warning"]),
            "gpa_min": min((x["cgpa"] for x in log if x["cgpa"] is not None), default=None),
            "gpa_max": max((x["cgpa"] for x in log if x["cgpa"] is not None), default=None)}


def _order(label: str | None) -> tuple:
    if not label:
        return (9999, 9)
    word, years = label.split(" ", 1)
    start = int(years[:4])
    return (start, {"الخريف": 0, "الربيع": 1, "الصيفي": 2}[word])


